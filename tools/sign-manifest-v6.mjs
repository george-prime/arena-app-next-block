// SIGNS NEXTBLOCK'S MANIFEST VERSION 6: version 5 in every term but the game's mark - the square icon and the wordmark with their
// comments cleaned (clients.json markV6); the same two cores and their browser bundles (pinnedV5). Its parent is version 5.
//   node tools/sign-manifest-v6.mjs <dev dir holding game-dev.pkcs8>
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { gameDevKey, signManifest } from 'arena-sdk/manifest-sign';
import { MANIFEST_V5, GAME_ID_V5 } from '../plugin/nextblock-v5.js';
import { encodeManifest, gameIdOf, manifestStands } from 'arena-sdk/manifest';
import { toHex, fromHex } from 'arena-sdk/hash';
import { verifyEd25519 } from 'arena-sdk/ed25519';

const [dir] = process.argv.slice(2);
if (!dir) { console.error('usage: node sign-manifest-v6.mjs <dev dir holding game-dev.pkcs8>'); process.exit(2); }
const dev = gameDevKey(readFileSync(join(dir, 'game-dev.pkcs8')));
if (toHex(dev.pubkey) !== toHex(MANIFEST_V5.gameDevPubkey)) throw new Error(`that key is not nextblock's developer key ${toHex(MANIFEST_V5.gameDevPubkey).slice(0, 16)}`);
const CLIENTS = JSON.parse(readFileSync(new URL('../plugin/clients.json', import.meta.url), 'utf8'));
const clients = [...Object.values(CLIENTS.pinnedV5).flat(), ...Object.values(CLIENTS.markV6).flat()];
const sorted = (hs) => [...hs].sort();
const { signature, ...v5body } = MANIFEST_V5;
void signature;
const body = { ...v5body, version: MANIFEST_V5.version + 1, parentManifestId: GAME_ID_V5, clients: sorted(clients).map(fromHex) };
const manifest = signManifest(body, dev);
const stands = manifestStands(manifest, { verify: verifyEd25519, parentOf: (id) => (toHex(id) === toHex(GAME_ID_V5) ? MANIFEST_V5 : null) });
if (!stands.ok) throw new Error(stands.why);
const id = toHex(gameIdOf(manifest));
writeFileSync(new URL('../plugin/nextblock-v6.js', import.meta.url), `// GENERATED by tools/sign-manifest-v6.mjs with the dev client's signer - do not edit by hand. PUBLIC BYTES ONLY:
// nextblock's GameManifest version 6: version 5 (${toHex(GAME_ID_V5)}) in every term but the game's mark - the icon and the wordmark
// with their comments cleaned. Signed by its developer key ${toHex(dev.pubkey)}; a node verifies it.
// game_id ${id}
import { GAME as V1 } from './nextblock.js';
import { NEXTBLOCK_CORES_V5 } from './truck-cores.js';
import { decodeManifest, gameIdOf } from 'arena-sdk/manifest';
import { fromHex } from 'arena-sdk/hash';

export const MANIFEST_V6_HEX = '${toHex(encodeManifest(manifest))}';
export const MANIFEST_V6 = decodeManifest(fromHex(MANIFEST_V6_HEX));
export const GAME_ID_V6 = gameIdOf(MANIFEST_V6);
/** What a launcher loads from this module (ARENA_APPS): the registration. */
export const GAME = Object.freeze({ ...V1, manifest: MANIFEST_V6, gameId: GAME_ID_V6, cores: NEXTBLOCK_CORES_V5 });
`);
console.log(`nextblock v${body.version}: parent ${toHex(GAME_ID_V5).slice(0, 16)}, ${body.cores.length} cores, ${body.clients.length} clients, game_id ${id}`);
