// SIGNS NEXTBLOCK'S MANIFEST VERSION 7: version 6 in every term but its core and that core's browser bundle - 8cbc74b2,
// 0847c99f with a door per player in a shared world (truck-cores.js NEXTBLOCK_CORES_V7, clients.json pinnedV7) - beside the game's
// mark. Its parent is version 6. Writes plugin/nextblock-v7.js and plugin/known-v7.js, both generated, public bytes only.
//   node tools/sign-manifest-v7.mjs <dev dir holding game-dev.pkcs8>
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { MANIFEST_V6, GAME_ID_V6 } from '../plugin/nextblock-v6.js';
import { NEXTBLOCK_CORES_V7 } from '../plugin/truck-cores.js';
import { gameDevKey, signManifest } from 'arena-sdk/manifest-sign';
import { encodeManifest, gameIdOf, manifestStands } from 'arena-sdk/manifest';
import { toHex, fromHex } from 'arena-sdk/hash';
import { verifyEd25519 } from 'arena-sdk/ed25519';

const sorted = (hs) => [...hs].sort();

/** Version 7's terms, unsigned: what the developer's key signs, and all a test can hold it to before it is signed. */
export function manifestV7Body() {
  const CLIENTS = JSON.parse(readFileSync(new URL('../plugin/clients.json', import.meta.url), 'utf8'));
  const { signature, ...v6body } = MANIFEST_V6;
  void signature;
  return {
    ...v6body,
    version: MANIFEST_V6.version + 1,
    parentManifestId: GAME_ID_V6,
    cores: sorted([...NEXTBLOCK_CORES_V7.keys()]).map((h) => ({ hash: fromHex(h), configs: sorted([...NEXTBLOCK_CORES_V7.get(h).configs.keys()]).map(fromHex) })),
    clients: sorted([...Object.values(CLIENTS.pinnedV7).flat(), ...Object.values(CLIENTS.markV6).flat()]).map(fromHex),
  };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const [dir] = process.argv.slice(2);
  if (!dir) { console.error('usage: node sign-manifest-v7.mjs <dev dir holding game-dev.pkcs8>'); process.exit(2); }
  const dev = gameDevKey(readFileSync(join(dir, 'game-dev.pkcs8')));
  if (toHex(dev.pubkey) !== toHex(MANIFEST_V6.gameDevPubkey)) throw new Error(`that key is not nextblock's developer key ${toHex(MANIFEST_V6.gameDevPubkey).slice(0, 16)}`);
  const body = manifestV7Body();
  const manifest = signManifest(body, dev);
  const stands = manifestStands(manifest, { verify: verifyEd25519, parentOf: (id) => (toHex(id) === toHex(GAME_ID_V6) ? MANIFEST_V6 : null) });
  if (!stands.ok) throw new Error(stands.why);
  const id = toHex(gameIdOf(manifest));
  writeFileSync(new URL('../plugin/nextblock-v7.js', import.meta.url), `// GENERATED by tools/sign-manifest-v7.mjs with the dev client's signer - do not edit by hand. PUBLIC BYTES ONLY:
// nextblock's GameManifest version 7: version 6 (${toHex(GAME_ID_V6)}) in every term but its core and that core's bundle - 8cbc74b2,
// a door per player in a shared world. Signed by its developer key ${toHex(dev.pubkey)}; a node verifies it.
// game_id ${id}
import { GAME as V1 } from './nextblock.js';
import { NEXTBLOCK_CORES_V7 } from './truck-cores.js';
import { decodeManifest, gameIdOf } from 'arena-sdk/manifest';
import { fromHex } from 'arena-sdk/hash';

export const MANIFEST_V7_HEX = '${toHex(encodeManifest(manifest))}';
export const MANIFEST_V7 = decodeManifest(fromHex(MANIFEST_V7_HEX));
export const GAME_ID_V7 = gameIdOf(MANIFEST_V7);
/** What a launcher loads from this module (ARENA_APPS): the registration. */
export const GAME = Object.freeze({ ...V1, manifest: MANIFEST_V7, gameId: GAME_ID_V7, cores: NEXTBLOCK_CORES_V7 });
`);
  writeFileSync(new URL('../plugin/known-v7.js', import.meta.url), `// GENERATED by tools/sign-manifest-v7.mjs. WHAT A CLIENT LISTS OF NEXTBLOCK VERSION 7: its signed bytes and the configs it plays as one world
// per round, as known-v4.js lists version 4.
//
//   node packages/arena-protocol/tools/known-games.js packages/nextblock/plugin/known-v7.js
import { MANIFEST_V7_HEX } from './nextblock-v7.js';
import { NEXTBLOCK_CORES_V7 } from './truck-cores.js';

export const KNOWN_GAME = Object.freeze({
  manifestHex: MANIFEST_V7_HEX,
  sharedWorld: [...new Set([...NEXTBLOCK_CORES_V7.values()].flatMap((c) => [...c.configs].filter(([, cfg]) => cfg && cfg.worldShared).map(([h]) => h)))],
});
`);
  console.log(`nextblock v${body.version}: parent ${toHex(GAME_ID_V6).slice(0, 16)}, ${body.cores.length} cores, ${body.clients.length} clients, game_id ${id}`);
}
