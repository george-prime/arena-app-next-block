// SIGNS NEXTBLOCK'S MANIFEST VERSION 5 (kanban #523: names, ticket numbers and blwp out of the files a game id commits to): version 4
// in every term but its cores and its clients - the two cores with their comments cleaned (a5c5766a the truck, 0847c99f the truck
// that knows the larger truck; truck-cores.js NEXTBLOCK_CORES_V5) and their browser bundles (clients.json pinnedV5) beside the
// game's mark, none of the blwp-core.js bundles. Its parent is version 4, so it stands only on top of it.
//   node tools/sign-manifest-v5.mjs <dev dir holding game-dev.pkcs8>
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { gameDevKey, signManifest } from 'arena-sdk/manifest-sign';
import { MANIFEST_V4, GAME_ID_V4 } from '../plugin/nextblock-v4.js';
import { NEXTBLOCK_CORES_V5 } from '../plugin/truck-cores.js';
import { encodeManifest, gameIdOf, manifestStands } from 'arena-sdk/manifest';
import { toHex, fromHex } from 'arena-sdk/hash';
import { verifyEd25519 } from 'arena-sdk/ed25519';

const [dir] = process.argv.slice(2);
if (!dir) { console.error('usage: node sign-manifest-v5.mjs <dev dir holding game-dev.pkcs8>'); process.exit(2); }
const dev = gameDevKey(readFileSync(join(dir, 'game-dev.pkcs8')));
if (toHex(dev.pubkey) !== toHex(MANIFEST_V4.gameDevPubkey)) throw new Error(`that key is not nextblock's developer key ${toHex(MANIFEST_V4.gameDevPubkey).slice(0, 16)}`);
const CLIENTS = JSON.parse(readFileSync(new URL('../plugin/clients.json', import.meta.url), 'utf8'));
const mark = Object.entries(CLIENTS.pinned).filter(([f]) => f !== 'blwp-core.js').flatMap(([, hs]) => hs);
const clients = [...Object.values(CLIENTS.pinnedV5).flat(), ...mark];
const sorted = (hs) => [...hs].sort();
const { signature, ...v4body } = MANIFEST_V4;
void signature;
const body = {
  ...v4body,
  version: MANIFEST_V4.version + 1,
  parentManifestId: GAME_ID_V4,
  cores: sorted([...NEXTBLOCK_CORES_V5.keys()]).map((h) => ({ hash: fromHex(h), configs: sorted([...NEXTBLOCK_CORES_V5.get(h).configs.keys()]).map(fromHex) })),
  clients: sorted(clients).map(fromHex),
};
const manifest = signManifest(body, dev);
const stands = manifestStands(manifest, { verify: verifyEd25519, parentOf: (id) => (toHex(id) === toHex(GAME_ID_V4) ? MANIFEST_V4 : null) });
if (!stands.ok) throw new Error(stands.why);
const id = toHex(gameIdOf(manifest));
writeFileSync(new URL('../plugin/nextblock-v5.js', import.meta.url), `// GENERATED by tools/sign-manifest-v5.mjs with the dev client's signer - do not edit by hand. PUBLIC BYTES ONLY:
// nextblock's GameManifest version 5 (kanban #523): version 4 (${toHex(GAME_ID_V4)}) in every term but its cores and clients - the
// cores with their comments cleaned (a5c5766a, 0847c99f) and their bundles. Signed by its developer key ${toHex(dev.pubkey)}; a node verifies it.
// game_id ${id}
import { GAME as V1 } from './nextblock.js';
import { NEXTBLOCK_CORES_V5 } from './truck-cores.js';
import { decodeManifest, gameIdOf } from 'arena-sdk/manifest';
import { fromHex } from 'arena-sdk/hash';

export const MANIFEST_V5_HEX = '${toHex(encodeManifest(manifest))}';
export const MANIFEST_V5 = decodeManifest(fromHex(MANIFEST_V5_HEX));
export const GAME_ID_V5 = gameIdOf(MANIFEST_V5);
/** What a launcher loads from this module (ARENA_APPS): the registration. */
export const GAME = Object.freeze({ ...V1, manifest: MANIFEST_V5, gameId: GAME_ID_V5, cores: NEXTBLOCK_CORES_V5 });
`);
console.log(`nextblock v${body.version}: parent ${toHex(GAME_ID_V4).slice(0, 16)}, ${body.cores.length} cores, ${body.clients.length} clients, game_id ${id}`);
